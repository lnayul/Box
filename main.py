# ============================================================
# 🎬 어제의 박스오피스
# 영화진흥위원회(KOBIS) Open API를 사용하는 Streamlit 앱
#
# 초보자용 설명:
# - 한국 시간 기준 '어제'의 영화 박스오피스를 가져옵니다.
# - KOBIS 인증키는 Streamlit Secrets에서 가져옵니다.
# - 인증키를 코드에 직접 적지 않습니다.
# - 같은 날짜의 결과는 1시간 동안 캐시합니다.
# ============================================================


# ------------------------------------------------------------
# 1. 필요한 라이브러리 불러오기
# ------------------------------------------------------------

import requests
import pandas as pd
import streamlit as st

from datetime import datetime, timedelta
from zoneinfo import ZoneInfo


# ------------------------------------------------------------
# 2. Streamlit 화면 기본 설정
# ------------------------------------------------------------

st.set_page_config(
    page_title="어제의 박스오피스",
    page_icon="🎬",
    layout="wide"
)


# ------------------------------------------------------------
# 3. 앱 제목
# ------------------------------------------------------------

st.title("🎬 어제의 박스오피스")
st.caption("영화진흥위원회(KOBIS) 일일 박스오피스")


# ------------------------------------------------------------
# 4. 한국 시간 기준으로 '어제' 계산
# ------------------------------------------------------------
#
# Streamlit Cloud의 서버가 한국 시간이라는 보장이 없습니다.
# 따라서 반드시 Asia/Seoul 시간대를 사용합니다.
#
# 예를 들어 한국 시간이 9월 7일이면
# 조회 날짜는 9월 6일이 됩니다.
# ------------------------------------------------------------

korea_now = datetime.now(
    ZoneInfo("Asia/Seoul")
)

yesterday = korea_now - timedelta(days=1)

# KOBIS API가 요구하는 날짜 형식
# 예: 20260906
target_date = yesterday.strftime("%Y%m%d")

# 화면에 표시할 날짜
# 예: 2026년 09월 06일
display_date = yesterday.strftime(
    "%Y년 %m월 %d일"
)


# ------------------------------------------------------------
# 5. 조회 날짜 표시
# ------------------------------------------------------------

st.subheader(
    f"📅 {display_date} 박스오피스"
)


# ------------------------------------------------------------
# 6. Streamlit Secrets에서 KOBIS 인증키 가져오기
# ------------------------------------------------------------
#
# Streamlit Cloud에서 다음과 같이 등록해야 합니다.
#
# Settings → Secrets
#
# KOBIS_KEY = "본인의_KOBIS_인증키"
#
# 인증키를 이 코드에 직접 적으면 안 됩니다.
# ------------------------------------------------------------

try:

    API_KEY = st.secrets["KOBIS_KEY"]

except Exception:

    st.error(
        "🔑 KOBIS 인증키를 찾을 수 없습니다."
    )

    st.markdown(
        """
        ### 🔎 확인해 주세요

        Streamlit Cloud에서 다음 메뉴로 이동하세요.

        **Settings → Secrets**

        그리고 아래 형식으로 등록되어 있어야 합니다.

        ```text
        KOBIS_KEY = "본인의_KOBIS_인증키"
        ```

        인증키의 앞뒤에 불필요한 공백이 없는지도 확인해 주세요.
        """
    )

    st.stop()


# ------------------------------------------------------------
# 7. KOBIS API 주소
# ------------------------------------------------------------

KOBIS_API_URL = (
    "https://www.kobis.or.kr/"
    "kobisopenapi/webservice/rest/boxoffice/"
    "searchDailyBoxOfficeList.json"
)


# ============================================================
# 8. KOBIS API 호출 함수
# ============================================================
#
# @st.cache_data(ttl=3600)
#
# 이 설정은 같은 입력값으로 함수를 다시 실행할 때
# 결과를 약 1시간 동안 기억하도록 합니다.
#
# 따라서 같은 날짜를 다시 조회하면
# KOBIS API를 매번 새로 호출하지 않습니다.
# ------------------------------------------------------------

@st.cache_data(ttl=3600)
def get_boxoffice(target_date, api_key):

    # API에 전달할 값
    params = {
        "key": api_key,
        "targetDt": target_date
    }


    # --------------------------------------------------------
    # API 요청
    # --------------------------------------------------------

    try:

        response = requests.get(
            KOBIS_API_URL,
            params=params,
            timeout=10
        )

    except requests.exceptions.Timeout:

        return None, (
            "KOBIS API 요청 시간이 초과되었습니다."
        )

    except requests.exceptions.ConnectionError:

        return None, (
            "KOBIS 서버에 연결하지 못했습니다."
        )

    except requests.exceptions.RequestException as e:

        return None, (
            f"API 요청 중 문제가 발생했습니다.\n\n{e}"
        )


    # --------------------------------------------------------
    # HTTP 상태 코드 확인
    # --------------------------------------------------------
    #
    # 일반적으로 정상 응답은 200입니다.
    # 다만 KOBIS에서는 인증키가 잘못되어도
    # HTTP 상태코드가 200으로 올 수 있습니다.
    # 따라서 아래의 faultInfo도 반드시 확인합니다.
    # --------------------------------------------------------

    if response.status_code != 200:

        return None, (
            f"KOBIS 서버에서 HTTP "
            f"{response.status_code} 응답을 반환했습니다."
        )


    # --------------------------------------------------------
    # JSON 데이터로 변환
    # --------------------------------------------------------

    try:

        data = response.json()

    except ValueError:

        return None, (
            "KOBIS 서버에서 JSON 형식의 데이터를 "
            "받지 못했습니다."
        )


    # --------------------------------------------------------
    # KOBIS 오류 확인
    # --------------------------------------------------------
    #
    # 인증키가 틀린 경우에도 HTTP 200이 올 수 있습니다.
    # 이런 경우 응답 안에 faultInfo가 들어옵니다.
    # --------------------------------------------------------

    if "faultInfo" in data:

        fault = data["faultInfo"]

        error_code = fault.get(
            "errorCode",
            "알 수 없음"
        )

        error_message = fault.get(
            "message",
            "오류 메시지가 없습니다."
        )

        return None, (
            "KOBIS API 오류가 발생했습니다.\n\n"
            f"오류 코드: {error_code}\n\n"
            f"오류 내용: {error_message}"
        )


    # --------------------------------------------------------
    # boxOfficeResult가 있는지 확인
    # --------------------------------------------------------

    if "boxOfficeResult" not in data:

        return None, (
            "KOBIS 응답에 boxOfficeResult가 없습니다."
        )


    boxoffice = data["boxOfficeResult"]


    # --------------------------------------------------------
    # 영화 목록 가져오기
    # --------------------------------------------------------

    movies = boxoffice.get(
        "dailyBoxOfficeList",
        []
    )


    # --------------------------------------------------------
    # 영화 목록이 비어 있는 경우
    # --------------------------------------------------------

    if not movies:

        return None, (
            "조회된 영화 목록이 없습니다."
        )


    # 정상적으로 영화 목록 반환
    return movies, None


# ============================================================
# 9. API 실행
# ============================================================

movies, error = get_boxoffice(
    target_date,
    API_KEY
)


# ============================================================
# 10. API 오류가 발생한 경우
# ============================================================

if error:

    st.error(
        "❌ 박스오피스 정보를 가져오지 못했습니다."
    )

    st.warning(
        f"""
        **오류 내용**

        {error}
        """
    )


    st.markdown("### 🔎 확인해 보세요")

    st.markdown(
        """
        **① KOBIS 인증키 확인**

        Streamlit Cloud의

        `Settings → Secrets`

        에서 `KOBIS_KEY`가 등록되어 있는지 확인하세요.


        **② 인증키 확인**

        KOBIS에서 발급받은 인증키가 정확한지 확인하세요.

        인증키를 복사할 때 앞뒤에 불필요한 공백이나
        따옴표가 잘못 들어가지 않았는지도 확인하세요.


        **③ 조회 날짜 확인**

        이 앱은 오늘 날짜가 아니라
        **한국 시간 기준 어제 날짜**를 자동으로 조회합니다.


        **④ KOBIS 서버 상태 확인**

        일시적으로 KOBIS API 서버에 연결되지 않을 수도 있습니다.

        잠시 후 페이지를 새로고침해서 다시 시도해 보세요.


        **⑤ 영화 목록 확인**

        API 연결은 성공했지만 영화 목록이 비어 있다면
        해당 날짜의 데이터가 아직 제공되지 않았거나
        KOBIS API 응답에 문제가 있을 수 있습니다.
        """
    )


    st.caption(
        f"한국 시간 기준 조회 날짜: {target_date}"
    )

    st.stop()


# ============================================================
# 11. API 결과를 DataFrame으로 변환
# ============================================================

df = pd.DataFrame(movies)


# ============================================================
# 12. 숫자 데이터를 숫자형으로 변환
# ============================================================
#
# KOBIS API에서는 숫자도 문자열로 전달됩니다.
#
# 예:
# "12345" → 12345
#
# 숫자형으로 바꿔야 관객수 기준 정렬과 그래프가
# 제대로 작동합니다.
# ------------------------------------------------------------

number_columns = [
    "rank",
    "rankInten",
    "audiCnt",
    "audiAcc",
    "scrnCnt",
    "showCnt"
]


for column in number_columns:

    if column in df.columns:

        df[column] = pd.to_numeric(
            df[column],
            errors="coerce"
        )


# ============================================================
# 13. 박스오피스 순위순으로 정렬
# ============================================================

df = df.sort_values(
    by="rank",
    ascending=True
).reset_index(drop=True)


# ============================================================
# 14. 1위 영화 정보
# ============================================================

first_movie = df.iloc[0]

first_movie_name = first_movie["movieNm"]


# ============================================================
# 15. 어제의 1위 표시
# ============================================================

st.markdown("---")

st.header("🏆 어제의 1위")

st.subheader(
    f"🥇 {first_movie_name}"
)


# ============================================================
# 16. 1위 영화 지표 카드 3개
# ============================================================

col1, col2, col3 = st.columns(3)


# ------------------------------------------------------------
# 카드 1: 어제 관객수
# ------------------------------------------------------------

with col1:

    st.metric(
        label="👥 어제 관객수",
        value=f"{int(first_movie['audiCnt']):,}명"
    )


# ------------------------------------------------------------
# 카드 2: 누적 관객수
# ------------------------------------------------------------

with col2:

    st.metric(
        label="🎟️ 누적 관객수",
        value=f"{int(first_movie['audiAcc']):,}명"
    )


# ------------------------------------------------------------
# 카드 3: 스크린 수
# ------------------------------------------------------------

with col3:

    st.metric(
        label="🖥️ 스크린 수",
        value=f"{int(first_movie['scrnCnt']):,}개"
    )


# ============================================================
# 17. 전체 박스오피스 표
# ============================================================

st.markdown("---")

st.header("📋 전체 박스오피스")


# ------------------------------------------------------------
# 화면에 보여줄 열만 선택
# ------------------------------------------------------------

table_df = df[
    [
        "rank",
        "movieNm",
        "openDt",
        "audiCnt",
        "audiAcc",
        "scrnCnt"
    ]
].copy()


# ------------------------------------------------------------
# 한국어 열 이름으로 변경
# ------------------------------------------------------------

table_df.columns = [
    "순위",
    "영화명",
    "개봉일",
    "관객수",
    "누적관객",
    "스크린수"
]


# ------------------------------------------------------------
# 표 표시
# ------------------------------------------------------------

st.dataframe(
    table_df.style.format(
        {
            "순위": "{:.0f}",
            "관객수": "{:,.0f}",
            "누적관객": "{:,.0f}",
            "스크린수": "{:,.0f}"
        }
    ),
    use_container_width=True,
    hide_index=True
)


# ============================================================
# 18. 관객수 TOP 5
# ============================================================

st.markdown("---")

st.header("📊 관객수 TOP 5")


# ------------------------------------------------------------
# 중요!
#
# 영화명 가나다순이 아닙니다.
#
# audiCnt = 해당 날짜의 관객수
#
# 관객수가 많은 영화부터 5편을 선택합니다.
# ------------------------------------------------------------

top5 = (
    df
    .nlargest(
        5,
        "audiCnt"
    )
    .copy()
)


# ============================================================
# 19. 그래프에 표시할 이름 만들기
# ============================================================
#
# 단순히 영화명만 표시하면 순위를 확인하기 어려울 수 있어서
# "1위 영화명", "2위 영화명" 형태로 표시합니다.
# ------------------------------------------------------------

top5["순위_영화명"] = (
    top5["rank"]
    .astype(int)
    .astype(str)
    + "위 "
    + top5["movieNm"].astype(str)
)


# ============================================================
# 20. 그래프 데이터 만들기
# ============================================================
#
# 관객수가 적은 영화부터 큰 영화 순서로 정렬합니다.
#
# 이렇게 하면 막대그래프에서
# 관객수가 가장 많은 영화가 위쪽에 표시되도록
# 구성할 수 있습니다.
# ------------------------------------------------------------

chart_df = (
    top5
    .sort_values(
        by="audiCnt",
        ascending=True
    )
    [
        [
            "순위_영화명",
            "audiCnt"
        ]
    ]
    .set_index("순위_영화명")
)


# ============================================================
# 21. 관객수 막대그래프
# ============================================================

st.bar_chart(
    chart_df,
    x_label="영화",
    y_label="관객수(명)"
)


# ============================================================
# 22. TOP 5 관객수 숫자도 표시
# ============================================================

st.markdown("#### 🏆 관객수 순위")


# 관객수가 많은 순서로 다시 정렬
top5_display = (
    top5
    .sort_values(
        by="audiCnt",
        ascending=False
    )
)


for _, movie in top5_display.iterrows():

    rank = int(movie["rank"])

    movie_name = movie["movieNm"]

    audience = int(movie["audiCnt"])

    st.write(
        f"**{rank}위 {movie_name}** "
        f"— {audience:,}명"
    )


# ============================================================
# 23. 하단 안내
# ============================================================

st.markdown("---")

st.caption(
    f"📌 한국 시간 기준 조회 날짜: {display_date}"
)

st.caption(
    "KOBIS Open API 데이터를 이용합니다."
)

st.caption(
    "같은 날짜의 데이터는 약 1시간 동안 캐시되어 "
    "불필요한 API 재호출을 줄입니다."
)
